# 倾向于"宁可误判也不漏判"。命中后只是温柔地暂停并给出求助资源，代价很低。
_PATTERNS = [
    "想死", "不想活", "活不下去", "不想活了", "不如死了", "死了算了", "死了好了",
    "一了百了", "结束生命", "结束自己", "了结自己", "了结生命", "轻生", "自杀",
    "自尽", "寻死", "活着没意思", "活着没意义", "不想再活", "想结束这一切",
    "想消失", "不想醒来", "撑不下去了", "自残", "自伤", "伤害自己",
    "kill myself", "want to die", "end my life", "suicide", "self harm",
    "self-harm", "cut myself", "don't want to live",
]


def is_crisis(text: str) -> bool:
    if not text:
        return False
    t = text.lower()
    return any(p in t for p in _PATTERNS)


